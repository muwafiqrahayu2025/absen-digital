import React, { useState, useEffect } from "react";
import { dbRealtime } from "../../lib/firebase";
import { ref, onValue, off } from "firebase/database";
import { Building2, Search, Calendar, Users, Mail, ShieldCheck, ToggleLeft, ToggleRight, Info } from "lucide-react";
import { useGlobalSettings } from "../../hooks/useGlobalSettings";

export function ManageTenants() {
  const [tenants, setTenants] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [searchQuery, setSearchQuery] = useState("");
  const { settings, loading: settingsLoading, updateSettings } = useGlobalSettings();

  useEffect(() => {
    const tenantsRef = ref(dbRealtime, 'tenants');
    const unsubscribe = onValue(tenantsRef, (snapshot) => {
      if (snapshot.exists()) {
        const data = snapshot.val();
        const tenantsArray = Object.keys(data).map(key => {
          const tenantData = data[key];
          
          // Parse timestamp from tenant ID (format: tenant_{timestamp_radix36}_{random})
          let registrationDate = "Tanggal tidak tersedia";
          try {
            const parts = key.split('_');
            if (parts.length > 1) {
              const timestamp36 = parts[1];
              // The radix 36 timestamp was generated by Date.now().toString(36)
              const timestamp = parseInt(timestamp36, 36);
              if (!isNaN(timestamp)) {
                registrationDate = new Date(timestamp).toLocaleDateString('id-ID', {
                  day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit'
                });
              }
            }
          } catch (e) {
            console.error("Failed to parse tenant date", e);
          }

          // Count users
          const userCount = tenantData.users ? Object.keys(tenantData.users).length : 0;

          return {
            id: key,
            name: tenantData.school?.name || "Nama Instansi Belum Diatur",
            email: tenantData.school?.email || "-",
            registrationDate,
            userCount,
            raw: tenantData
          };
        });
        
        // Sort by registration date descending (newest first)
        tenantsArray.sort((a, b) => b.id.localeCompare(a.id));
        
        setTenants(tenantsArray);
      } else {
        setTenants([]);
      }
      setLoading(false);
    }, (error) => {
      console.error("Error fetching tenants:", error);
      setLoading(false);
    });

    return () => {
      off(tenantsRef, "value", unsubscribe);
    };
  }, []);

  const query = searchQuery.toLowerCase();
  const filteredTenants = tenants.filter(t => 
    t.name.toLowerCase().includes(query) || 
    t.id.toLowerCase().includes(query) ||
    t.email.toLowerCase().includes(query)
  );

  return (
    <div className="space-y-6 animate-fade-in">
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 bg-white p-6 rounded-3xl border border-slate-100 shadow-sm">
        <div>
          <h2 className="text-2xl font-black text-slate-800 tracking-tight flex items-center gap-2">
            <ShieldCheck className="text-indigo-600" size={28} />
            Daftar Klien (Tenants)
          </h2>
          <p className="text-sm text-slate-400 mt-0.5">
            Monitoring seluruh instansi yang terdaftar di dalam platform SaaS. Akses eksklusif Super Admin.
          </p>
        </div>
        <div className="flex flex-col items-end gap-2">
          <div className="bg-indigo-50 text-indigo-700 px-4 py-2 rounded-xl font-bold text-sm border border-indigo-100 flex items-center gap-2">
            <Building2 size={16} />
            Total Instansi: {tenants.length}
          </div>
          
          <div className="bg-white border border-slate-200 px-4 py-2.5 rounded-xl flex items-center gap-3 w-full sm:w-auto mt-2">
            <div>
              <div className="text-xs font-bold text-slate-800">Alternatif WA.me Klien</div>
              <div className="text-[10px] text-slate-500">Buka link wa.me jika klien tidak punya API</div>
            </div>
            <button
              disabled={settingsLoading}
              onClick={() => updateSettings({ wa_fallback_enabled: !settings.wa_fallback_enabled })}
              className={`ml-auto transition-colors focus:outline-none disabled:opacity-50 ${settings.wa_fallback_enabled ? 'text-emerald-500' : 'text-slate-300'}`}
            >
              {settings.wa_fallback_enabled ? <ToggleRight size={32} /> : <ToggleLeft size={32} />}
            </button>
          </div>
        </div>
      </div>

      <div className="bg-white p-4 rounded-2xl border border-slate-150 flex flex-col sm:flex-row gap-3">
        <div className="flex-1 relative">
          <Search size={16} className="absolute left-3.5 top-1/2 transform -translate-y-1/2 text-slate-400 pointer-events-none" />
          <input
            type="text"
            placeholder="Cari berdasarkan nama instansi, ID, atau email..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full pl-10 pr-4 py-2 border border-slate-200 rounded-xl outline-none text-xs bg-slate-50/50"
          />
        </div>
      </div>

      <div className="bg-white rounded-3xl border border-slate-200 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs font-sans">
            <thead className="bg-[#17a2b8] text-white">
              <tr>
                <th className="p-4 w-16 text-center">No</th>
                <th className="p-4">Informasi Instansi / Tenant</th>
                <th className="p-4">Email Admin Klien</th>
                <th className="p-4">Waktu Pendaftaran</th>
                <th className="p-4 text-center">Statistik</th>
                <th className="p-4 text-center">Status Lisensi</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 text-slate-700 font-medium">
              {loading ? (
                <tr><td colSpan={6} className="p-8 text-center text-slate-400 font-bold animate-pulse">Memuat data clients...</td></tr>
              ) : filteredTenants.length === 0 ? (
                <tr><td colSpan={6} className="p-8 text-center text-slate-400">Tidak ada instansi yang ditemukan.</td></tr>
              ) : (
                filteredTenants.map((tenant, idx) => (
                  <tr key={tenant.id} className="hover:bg-slate-50/60 transition">
                    <td className="p-4 text-center text-slate-400 font-bold font-mono">{idx + 1}</td>
                    <td className="p-4">
                      <div className="font-extrabold text-slate-800 text-sm mb-0.5">{tenant.name}</div>
                      <div className="text-[10px] text-slate-400 font-mono tracking-wider">{tenant.id}</div>
                    </td>
                    <td className="p-4">
                      <div className="flex items-center gap-1.5 text-slate-600">
                        <Mail size={12} className="text-slate-400" />
                        {tenant.email}
                      </div>
                    </td>
                    <td className="p-4">
                      <div className="flex items-center gap-1.5 text-slate-600">
                        <Calendar size={12} className="text-slate-400" />
                        {tenant.registrationDate}
                      </div>
                    </td>
                    <td className="p-4 text-center">
                      <div className="inline-flex items-center gap-1.5 bg-sky-50 text-sky-700 border border-sky-100 px-2 py-1 rounded-lg text-[10px] font-bold">
                        <Users size={12} />
                        {tenant.userCount} Pegawai
                      </div>
                    </td>
                    <td className="p-4 text-center">
                      <span className="bg-emerald-50 text-emerald-700 border border-emerald-200 px-2.5 py-1 rounded-md text-[10px] font-black uppercase tracking-wider">
                        Aktif
                      </span>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
